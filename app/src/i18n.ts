const catalogs: Record<Locale, Messages> = { "pt-BR": ptBR, en };
const storageKey = "o2xml.locale";
let currentLocale: Locale = "pt-BR";

export function isLocale(value: string | null): value is Locale {
  return value !== null && supportedLocales.includes(value as Locale);
}

export function initializeLocale(storage: Pick<Storage, "getItem"> | null = null): Locale {
  try {
    const stored = storage?.getItem(storageKey) ?? null;
    currentLocale = isLocale(stored) ? stored : "pt-BR";
  } catch {
    currentLocale = "pt-BR";
  }
  return currentLocale;
}

export function getLocale(): Locale {
  return currentLocale;
}

export function persistLocale(locale: Locale, storage: Pick<Storage, "setItem"> | null): void {
  currentLocale = locale;
  try {
    storage?.setItem(storageKey, locale);
  } catch {
    // The selected language still applies to this session when storage is unavailable.
  }
}

export function t(key: MessageKey, parameters: Record<string, string | number> = {}): string {
  return catalogs[currentLocale][key].replace(/\{([A-Za-z]+)\}/gu, (placeholder, name: string) => {
    const value = parameters[name];
    return value === undefined ? placeholder : String(value);
  });
}
